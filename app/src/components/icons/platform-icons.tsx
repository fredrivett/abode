/**
 * Get the icon component for a platform.
 */
export function PlatformIcon({
  platform,
  className,
}: { platform: string; className?: string }) {
  switch (platform) {
    case "unsplash":
      return <UnsplashIcon className={className} />;
    case "flickr":
      return <FlickrIcon className={className} />;
    case "500px":
      return <FiveHundredPxIcon className={className} />;
    case "instagram":
      return <InstagramIcon className={className} />;
    case "twitter":
      return <TwitterIcon className={className} />;
    case "behance":
      return <BehanceIcon className={className} />;
    case "dribbble":
      return <DribbbleIcon className={className} />;
    case "pinterest":
      return <PinterestIcon className={className} />;
    case "deviantart":
      return <DeviantArtIcon className={className} />;
    case "artstation":
      return <ArtStationIcon className={className} />;
    default:
      return <Globe className={cn("size-4", className)} />;
  }
}
